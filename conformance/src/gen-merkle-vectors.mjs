// Generator for the DID→head Merkle commitment differential vectors (Phase 3 P3.2).
//
// Independently re-implements the pinned tree format (REFERENCE.md §4; mirrored in
// cairo/packages/plc_core/src/merkle.cairo) with raw node:crypto sha256 — no shared code
// with Cairo — and emits cairo/packages/plc_core/tests/merkle_vectors_generated.cairo.
// The Cairo merkle tests assert byte-identical leaf/node/root/proof, so the on-chain tree
// and any resolver computing it the same way agree. This is the format pin: changing it
// here forces a Cairo drift and a deliberate review.
//
// Format (RFC 6962 domain separation, odd-node promotion, entries sorted by did ascending):
//   leaf  = sha256( 0x00 ‖ did ‖ head_cid )
//   node  = sha256( 0x01 ‖ left ‖ right )
//   empty = sha256( "" )
//
// Run via `make gen-merkle-vectors`; CI asserts no drift.
import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const outPath = join(
  here,
  "..",
  "..",
  "cairo",
  "packages",
  "plc_core",
  "tests",
  "merkle_vectors_generated.cairo",
);

const sha256 = (buf) => createHash("sha256").update(buf).digest();
const utf8 = (s) => Buffer.from(s, "utf8");
const hex = (buf) => Buffer.from(buf).toString("hex");

const LEAF_PREFIX = Buffer.from([0x00]);
const NODE_PREFIX = Buffer.from([0x01]);

const leafHash = (did, head) =>
  sha256(Buffer.concat([LEAF_PREFIX, utf8(did), utf8(head)]));
const nodeHash = (l, r) => sha256(Buffer.concat([NODE_PREFIX, l, r]));
const emptyRoot = () => sha256(Buffer.alloc(0));

function merkleRoot(leaves) {
  if (leaves.length === 0) return emptyRoot();
  let level = leaves;
  while (level.length > 1) {
    const next = [];
    for (let i = 0; i < level.length; ) {
      if (i + 1 < level.length) {
        next.push(nodeHash(level[i], level[i + 1]));
        i += 2;
      } else {
        next.push(level[i]); // promote the odd node
        i += 1;
      }
    }
    level = next;
  }
  return level[0];
}

// Inclusion path for `index`: { sibling, sibling_is_left } per level; a promoted node
// contributes no step. Mirrors merkle.cairo::merkle_proof.
function merkleProof(leaves, index) {
  const proof = [];
  let level = leaves;
  let idx = index;
  while (level.length > 1) {
    const isRight = idx % 2 === 1;
    if (isRight) {
      proof.push({ sibling: level[idx - 1], sibling_is_left: true });
    } else if (idx + 1 < level.length) {
      proof.push({ sibling: level[idx + 1], sibling_is_left: false });
    }
    const next = [];
    for (let i = 0; i < level.length; ) {
      if (i + 1 < level.length) {
        next.push(nodeHash(level[i], level[i + 1]));
        i += 2;
      } else {
        next.push(level[i]);
        i += 1;
      }
    }
    level = next;
    idx = Math.floor(idx / 2);
  }
  return proof;
}

// Fixed entry set: real-shape did:plc strings (8 + 24 = 32 bytes) → base32 CID strings.
// Deliberately out of sorted order on input so the vector also pins the canonical sort.
const entriesRaw = [
  ["did:plc:ewvi7nxzyoun6zhxrhs64oiz", "bafyreigenesisalicexxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxa"],
  ["did:plc:7iza6de2dwap2sbkpav7c6c6", "bafyreigenesisbobxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxb"],
  ["did:plc:44tn5dyjrgw57aqqwm4z2tzp", "bafyreigenesiscarolxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxc"],
  ["did:plc:zzzzzzzzzzzzzzzzzzzzzzzz", "bafyreigenesisdavexxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxd"],
];

// Canonical order: sort entries by did ascending (bytewise on the utf8 string).
const entries = [...entriesRaw].sort((a, b) =>
  Buffer.compare(utf8(a[0]), utf8(b[0])),
);
const leaves = entries.map(([did, head]) => leafHash(did, head));
const root = merkleRoot(leaves);

// A single-entry tree (root == that leaf) and the empty tree, to pin the degenerate cases.
const single = [["did:plc:ewvi7nxzyoun6zhxrhs64oiz", entriesRaw[0][1]]];
const singleLeaves = single.map(([d, h]) => leafHash(d, h));
const singleRoot = merkleRoot(singleLeaves);

// Inclusion proof for one membership (index 1 in canonical order).
const proofIndex = 1;
const proof = merkleProof(leaves, proofIndex);

const entryLines = entriesRaw
  .map(([did, head]) => `        ("${did}", "${head}"),`)
  .join("\n");
const proofLines = proof
  .map(
    (s) =>
      `        ProofStep { sibling: from_hex(@"${hex(s.sibling)}"), sibling_is_left: ${s.sibling_is_left} },`,
  )
  .join("\n");

const out = `//! @generated by conformance/src/gen-merkle-vectors.mjs — DO NOT EDIT.
//!
//! DID→head Merkle commitment vectors (Phase 3 P3.2), computed with raw node:crypto sha256
//! independently of Cairo. Pins the tree format resolvers depend on:
//!   leaf = sha256(0x00 ‖ did ‖ head_cid), node = sha256(0x01 ‖ left ‖ right),
//!   entries sorted by did ascending, odd nodes promoted (RFC 6962).
//! Regenerate with \`make gen-merkle-vectors\`; CI fails if this drifts.

use plc_core::merkle::ProofStep;
use super::common::from_hex;

/// Map entries in INPUT (unsorted) order; the tree sorts by did before hashing.
pub fn merkle_entries() -> Array<(ByteArray, ByteArray)> {
    array![
${entryLines}
    ]
}

/// Expected root over \`merkle_entries()\` (canonical sorted order).
pub fn merkle_expected_root() -> ByteArray {
    from_hex(@"${hex(root)}")
}

/// Expected root of the single-entry tree (== that entry's leaf hash).
pub fn merkle_single_root() -> ByteArray {
    from_hex(@"${hex(singleRoot)}")
}

/// Expected root of the empty map: sha256("").
pub fn merkle_empty_root() -> ByteArray {
    from_hex(@"${hex(emptyRoot())}")
}

/// The canonical-order index whose inclusion proof is pinned below.
pub fn merkle_proof_index() -> usize {
    ${proofIndex}
}

/// Inclusion proof for \`merkle_proof_index()\` against \`merkle_expected_root()\`.
pub fn merkle_proof_steps() -> Array<ProofStep> {
    array![
${proofLines}
    ]
}
`;

writeFileSync(outPath, out);
console.log(`gen-merkle-vectors: wrote ${entriesRaw.length}-entry tree + proof to ${outPath}`);
console.log(`  root        = ${hex(root)}`);
console.log(`  single root = ${hex(singleRoot)}`);
console.log(`  empty root  = ${hex(emptyRoot())}`);
