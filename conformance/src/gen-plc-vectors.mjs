// PLC-op CID/DID acceptance gate: reads the committed corpus, re-validates every
// entry byte-for-byte against @ipld/dag-cbor + sha256, then emits the Cairo
// vector table consumed by snforge tests (REFERENCE.md §3, §5).
//
// Run via `make gen-plc-vectors`; CI asserts no drift with gen-plc-vectors-check.
// To refresh the corpus from scratch: make gen-plc-corpus (network-independent;
// uses @did-plc/lib internally).
import { encode } from "@ipld/dag-cbor";
import { CID } from "multiformats";
import { sha256 } from "multiformats/hashes/sha2";
import { base32 } from "multiformats/bases/base32";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const corpusPath = join(here, "..", "vectors", "plc-ops", "corpus.json");
const outPath = join(
  here,
  "..",
  "..",
  "cairo",
  "packages",
  "drisl",
  "tests",
  "plc_vectors_generated.cairo",
);

const corpus = JSON.parse(readFileSync(corpusPath, "utf8"));

const vectors = [];
for (const e of corpus) {
  // Re-encode with @ipld/dag-cbor and assert byte-identical to fixture.
  const reencoded = Buffer.from(encode(e.operation)).toString("hex");
  if (reencoded !== e.drisl_hex) {
    throw new Error(
      `[${e.label}] DRISL bytes mismatch: @ipld/dag-cbor re-encode ≠ corpus.\n` +
        `  corpus : ${e.drisl_hex.slice(0, 80)}...\n` +
        `  reencoded: ${reencoded.slice(0, 80)}...`,
    );
  }

  // Re-derive CID and assert it matches the corpus CID.
  const bytes = Buffer.from(e.drisl_hex, "hex");
  const digest = await sha256.digest(bytes);
  const cid = CID.create(1, 0x71 /* dag-cbor */, digest);
  const cidStr = cid.toString(base32);
  if (cidStr !== e.cid) {
    throw new Error(
      `[${e.label}] CID mismatch: recomputed=${cidStr}, corpus=${e.cid}`,
    );
  }

  // For genesis ops (prev: null), re-derive DID and assert it matches.
  const isGenesis =
    e.operation.prev === null || e.operation.prev === undefined;
  let didFragment = "";
  if (isGenesis) {
    const rawDigest = digest.digest; // raw 32-byte sha256
    // base32lower of first 15 bytes → 24 chars (drop 'b' multibase prefix).
    const encoded = base32.encode(rawDigest.slice(0, 15));
    didFragment = encoded.slice(1, 25);
    const derivedDid = `did:plc:${didFragment}`;
    if (derivedDid !== e.did) {
      throw new Error(
        `[${e.label}] DID mismatch: derived=${derivedDid}, corpus=${e.did}`,
      );
    }
  }

  vectors.push({
    label: e.label,
    drisl_hex: e.drisl_hex,
    cid_hex: e.cid_hex,
    is_genesis: isGenesis,
    did_fragment: didFragment,
  });
}

const lines = vectors.map(
  (v) =>
    `        PlcVector {
            drisl_hex: "${v.drisl_hex}",
            cid_hex: "${v.cid_hex}",
            is_genesis: ${v.is_genesis},
            did_fragment: "${v.did_fragment}",
        }, // ${v.label}`,
);

const out = `//! @generated by conformance/src/gen-plc-vectors.mjs — DO NOT EDIT.
//!
//! Source: conformance/vectors/plc-ops/corpus.json
//! ${vectors.length} real-structure PLC op vectors (CID/DID acceptance gate, REFERENCE.md §3, §5).
//! Each entry: CBOR bytes of the signed op, expected binary CIDv1 (dag-cbor/sha2-256),
//! and for genesis ops the expected 24-char DID fragment.
//! Regenerate with \`make gen-plc-vectors\`; CI fails if this drifts.

#[derive(Drop)]
pub struct PlcVector {
    pub drisl_hex: ByteArray,
    pub cid_hex: ByteArray,
    pub is_genesis: bool,
    pub did_fragment: ByteArray,
}

pub fn plc_vectors() -> Array<PlcVector> {
    array![
${lines.join("\n")}
    ]
}
`;

writeFileSync(outPath, out);
console.log(
  `gen-plc-vectors: ${vectors.length} PLC op vectors validated and written to ${outPath}`,
);
for (const v of vectors) {
  console.log(`  [${v.label}] genesis=${v.is_genesis}`);
}
