// Codegen: vendored DASL/dCBOR42 JSON vectors -> a Cairo source file the snforge
// conformance harness consumes (REFERENCE.md §3, §5). The Cairo VM has no filesystem at
// test time, so we emit the in-scope cases as (expected, hex) literals. The JSON under
// vectors/dasl-cbor stays the single source of truth — this file is DERIVED, never edited
// by hand (guardrail: CLAUDE.md). Run via `make gen-vectors`; CI asserts no drift.
//
// Profile selection: the suite is multi-spec (a single datum can be valid under rfc8949
// yet invalid under dag-cbor). We implement dag-cbor / DASL-CID, so we keep only cases
// whose `tags` intersect the dag-cbor family and drop cases meant for other profiles.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const vectorsDir = join(here, "..", "vectors", "dasl-cbor");
const outFile = join(
  here,
  "..",
  "..",
  "cairo",
  "packages",
  "drisl",
  "tests",
  "vectors_generated.cairo",
);

// dag-cbor is our target; `dasl-cid` is the DASL CID profile (a dag-cbor refinement);
// `basic` means "all specs agree". Cases tagged only for rfc8949 / dCBOR / CBOR-Core / CDE
// describe a DIFFERENT profile's expected outcome and must not drive our tests.
const IN_SCOPE = new Set(["dag-cbor", "dasl-cid", "basic"]);

const cases = [];
let dropped = 0;
for (const f of readdirSync(vectorsDir).sort()) {
  if (!f.endsWith(".json")) continue;
  const arr = JSON.parse(readFileSync(join(vectorsDir, f), "utf8"));
  for (const c of arr) {
    if (!Array.isArray(c.tags) || !c.tags.some((t) => IN_SCOPE.has(t))) {
      dropped += 1;
      continue;
    }
    if (!["roundtrip", "invalid_in", "invalid_out"].includes(c.type)) {
      throw new Error(`${f}: unknown case type ${c.type}`);
    }
    if (!/^[0-9a-f]*$/.test(c.data)) throw new Error(`${f}: data not lowercase hex`);
    cases.push({ file: f, ...c });
  }
}

const lines = cases.map(
  (c) => `        ('${c.type}', "${c.data}"), // ${c.file}: ${c.name}`,
);

const out = `//! @generated by conformance/src/gen-cairo-vectors.mjs — DO NOT EDIT.
//!
//! Source: conformance/vectors/dasl-cbor (hyphacoop/dasl-testing, commit 84a34aa).
//! ${cases.length} in-scope dag-cbor/DASL-CID cases (${dropped} other-profile cases dropped).
//! Regenerate with \`make gen-vectors\`; CI fails if this drifts from the JSON.

/// (expected, hex-encoded CBOR). expected is one of 'roundtrip' | 'invalid_in' | 'invalid_out'.
pub fn vectors() -> Array<(felt252, ByteArray)> {
    array![
${lines.join("\n")}
    ]
}
`;

writeFileSync(outFile, out);
console.log(`gen-cairo-vectors: ${cases.length} in-scope cases -> ${outFile} (${dropped} dropped)`);
