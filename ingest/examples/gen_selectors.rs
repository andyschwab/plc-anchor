//! Generate `witness-ts/src/selectors.ts` — the Starknet entrypoint selectors the witness
//! library calls to read the anchor.
//!
//! A selector is `starknet_keccak(name)`. Node's `crypto` provides SHA3-256 but **not**
//! Keccak-256 (different padding), so the witness library cannot compute selectors at runtime
//! without a keccak dependency — which would defeat its zero-dependency read path. Instead we
//! precompute them here with the **same** `starknet` crate the live ingest sink uses
//! (`get_selector_from_name`) and pin the result, exactly like the Merkle/op vectors.
//!
//! Run: `cargo run -p ingest --example gen_selectors --features live` (or `make gen-selectors`).
//! CI drift-gates the output so the pinned selectors can't silently diverge from the crate.

use std::fs;
use std::path::Path;

use starknet::core::utils::get_selector_from_name;

/// The anchor view entrypoints the witness reads (REFERENCE.md §3; `anchor.cairo`). Verify-on-read:
/// the witness reads the raw op log (`chain`) and re-derives heads itself — no head/root/proof
/// views.
const VIEWS: &[&str] = &["is_anchored", "chain"];

/// The anchor event names the witness filters `starknet_getEvents` on. A Cairo event variant's
/// first key is `starknet_keccak(name)` — the same function as an entrypoint selector — so the
/// console's refresh loop can ask "did any DID's log change since block N?" with a single events
/// query instead of re-reading every DID's `chain` each cycle (RPC cost). `Stored` fires on every
/// `submit_op` / `import` (`anchor.cairo`).
const EVENTS: &[&str] = &["Stored"];

fn main() {
    let mut entries = String::new();
    for name in VIEWS {
        let selector = get_selector_from_name(name).expect("valid entrypoint name");
        entries.push_str(&format!("  {name}: \"{selector:#x}\",\n"));
    }

    let mut event_entries = String::new();
    for name in EVENTS {
        let key = get_selector_from_name(name).expect("valid event name");
        event_entries.push_str(&format!("  {name}: \"{key:#x}\",\n"));
    }

    let out = format!(
        "// @generated by `cargo run -p ingest --example gen_selectors --features live` — DO NOT EDIT.\n\
//\n\
// Starknet entrypoint selectors = starknet_keccak(name). Node's crypto has no Keccak-256, so\n\
// these are precomputed with the same `starknet` crate the live ingest sink uses and pinned\n\
// here. Regenerate with `make gen-selectors`; CI fails on drift.\n\
\n\
/** Selector (felt hex) for each anchor view entrypoint the witness reads. */\n\
export const SELECTORS = {{\n{entries}}} as const;\n\
\n\
export type ViewName = keyof typeof SELECTORS;\n\
\n\
/** First-key selector (felt hex) for each anchor event the witness filters `getEvents` on. */\n\
export const EVENT_KEYS = {{\n{event_entries}}} as const;\n\
\n\
export type EventName = keyof typeof EVENT_KEYS;\n"
    );

    let path = Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .expect("repo root")
        .join("witness-ts/src/selectors.ts");
    fs::write(&path, out).expect("write selectors.ts");
    eprintln!(
        "gen_selectors: wrote {} selectors + {} event keys to {}",
        VIEWS.len(),
        EVENTS.len(),
        path.display()
    );
}
